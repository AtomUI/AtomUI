#!/usr/bin/env python3
"""Generate the Shadcn Tailwind palette from tailwindcss@4.3.5/theme.css."""

import argparse
import math
import re
from pathlib import Path

STOPS = (50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950)
NEUTRAL_FAMILIES = ("neutral", "stone", "zinc", "mauve", "olive", "mist", "taupe")
THEME_FAMILIES = (
    "amber", "blue", "cyan", "emerald", "fuchsia", "green", "indigo", "lime", "orange", "pink", "purple",
    "red", "rose", "sky", "teal", "violet", "yellow",
)
FAMILIES = NEUTRAL_FAMILIES + THEME_FAMILIES
OUTPUT = (Path(__file__).resolve().parents[1] / "src/DesignLanguages/Shadcn/AtomUI.DesignLanguages.Shadcn"
          / "TokenEvaluation/ShadcnTailwindPalette.cs")


def to_argb(lightness: str, chroma: str, hue: str) -> str:
    light = float(lightness.removesuffix("%"))
    if lightness.endswith("%"):
        light /= 100
    angle = 0.0 if hue == "none" else math.radians(float(hue))
    a = float(chroma) * math.cos(angle)
    b = float(chroma) * math.sin(angle)

    # Oklab to linear sRGB matrices. https://bottosson.github.io/posts/oklab/
    lms_l = (light + 0.3963377774 * a + 0.2158037573 * b) ** 3
    lms_m = (light - 0.1055613458 * a - 0.0638541728 * b) ** 3
    lms_s = (light - 0.0894841775 * a - 1.2914855480 * b) ** 3
    linear = (
        4.0767416621 * lms_l - 3.3077115913 * lms_m + 0.2309699292 * lms_s,
        -1.2684380046 * lms_l + 2.6097574011 * lms_m - 0.3413193965 * lms_s,
        -0.0041960863 * lms_l - 0.7034186147 * lms_m + 1.7076147010 * lms_s,
    )
    # Preserve the palette's 8-bit rounding and channel clipping.
    srgb = [12.92 * channel if channel <= 0.0031308 else 1.055 * channel ** (1 / 2.4) - 0.055
            for channel in linear]
    return "0xFF" + "".join(f"{round(min(1, max(0, channel)) * 255):02X}" for channel in srgb)


def read_colors(css: str) -> dict[tuple[str, int], str]:
    colors = {}
    for match in re.finditer(r"--color-([a-z]+)-(\d+):\s*oklch\(([^)]+)\);", css):
        family, stop, coordinates = match.groups()
        key = (family, int(stop))
        if family in FAMILIES and key[1] in STOPS:
            if key in colors:
                raise ValueError(f"Duplicate color {family}-{stop}")
            colors[key] = to_argb(*coordinates.split())
    missing = [f"{family}-{stop}" for family in FAMILIES for stop in STOPS if (family, stop) not in colors]
    if missing:
        raise ValueError("Missing Tailwind palette stops: " + ", ".join(missing))
    return colors


def generate(colors: dict[tuple[str, int], str]) -> str:
    arrays = []
    for family in FAMILIES:
        stops = ", ".join(f"C({colors[family, stop]})" for stop in STOPS)
        arrays.append(f"    private static readonly Color[] s_{family} = [{stops}];")
    arrays_text = "\n".join(arrays)
    family_entries = "\n".join(f'        ["{family}"] = s_{family},' for family in FAMILIES)
    neutral_list = ", ".join(f'"{family}"' for family in NEUTRAL_FAMILIES)
    theme_lines = [", ".join(f'"{family}"' for family in THEME_FAMILIES[:11]),
                   ", ".join(f'"{family}"' for family in THEME_FAMILIES[11:])]
    return f"""// <auto-generated />
// Generated from tailwindcss@4.3.5/theme.css by scripts/generate-shadcn-tailwind-palette.py.
using Avalonia.Media;

namespace AtomUI.DesignLanguages.Shadcn.TokenEvaluation;

/// <summary>
/// The Tailwind v4.3.5 colour scale: 24 families (7 neutral + 17 theme, red included), each with eleven
/// stops from 50 to 950. Every shadcn colour variable is one stop of one family.
/// </summary>
internal static class ShadcnTailwindPalette
{{
    // Order: 50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950.
{arrays_text}

    private static readonly Dictionary<string, Color[]> s_families = new(StringComparer.Ordinal)
    {{
{family_entries}
    }};

    /// <summary>The eleven stops of a family; throws for an unknown family name.</summary>
    public static IReadOnlyDictionary<string, Color[]> Families => s_families;

    /// <summary>Gets a single stop (<c>50..950</c>) of a family.</summary>
    public static Color Stop(string family, int stop)
    {{
        var index = StopIndex(stop);
        return s_families[family][index];
    }}

    internal static int StopIndex(int stop) => stop switch
    {{
        50 => 0, 100 => 1, 200 => 2, 300 => 3, 400 => 4, 500 => 5,
        600 => 6, 700 => 7, 800 => 8, 900 => 9, 950 => 10,
        _ => throw new ArgumentOutOfRangeException(nameof(stop), stop, "A Tailwind stop is one of 50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950.")
    }};

    /// <summary>The seven neutral families, in appendix A order.</summary>
    public static IReadOnlyList<string> NeutralFamilies {{ get; }} = [{neutral_list}];

    /// <summary>The seventeen theme families, in appendix B order.</summary>
    public static IReadOnlyList<string> ThemeFamilies {{ get; }} =
    [
        {theme_lines[0]},
        {theme_lines[1]}
    ];

    private static Color C(uint argb) => new((byte)(argb >> 24), (byte)(argb >> 16), (byte)(argb >> 8), (byte)argb);
}}
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("theme_css", type=Path, help="theme.css from tailwindcss 4.3.5")
    parser.add_argument("--output", type=Path, default=OUTPUT, help="path of the generated C# file")
    args = parser.parse_args()
    try:
        source = generate(read_colors(args.theme_css.read_text(encoding="utf-8")))
        args.output.write_text(source, encoding="utf-8")
    except (OSError, ValueError) as error:
        parser.error(str(error))


if __name__ == "__main__":
    main()
