using System.Text;
using AtomUI.SourceGeneration;

namespace AtomUI.Generator;

internal static class ControlTokenDefaultsWriter
{
    internal static void Write(GenerationOutput output, IEnumerable<ControlThemeInfo> controls)
    {
        var source = new StringBuilder("// <auto-generated />\n");
        var count = 0;
        foreach (var control in controls.Where(static control => control.OwnToken?.DefaultPlan is not null)
                     .OrderBy(static control => control.ControlTypeName, StringComparer.Ordinal))
        {
            var own = control.OwnToken!;
            var plan = own.DefaultPlan!;
            var hasNamespace = !string.IsNullOrEmpty(own.TokenNamespace);
            if (hasNamespace)
            {
                source.Append("namespace ").Append(own.TokenNamespace).AppendLine(" {");
            }
            source.Append("partial class ").Append(own.TokenName).AppendLine(" {");
            source.AppendLine("    public static void EvaluateDefaults(global::AtomUI.Theme.DesignTokens.AbstractControlDesignToken token,");
            source.AppendLine("        in global::AtomUI.Theme.DesignTokens.ControlTokenDefaultContext context, global::System.ReadOnlySpan<ulong> explicitOwnSlots)");
            source.AppendLine("    {");
            source.Append("        var value = (global::").Append(own.GetFullyQualifiedTokenTypeName()).AppendLine(")token;");
            foreach (var step in plan.Steps)
            {
                source.Append("        if (explicitOwnSlots.IsEmpty || (explicitOwnSlots[")
                    .Append(step.Slot >> 6).Append("] & (1UL << ").Append(step.Slot & 63).AppendLine(")) == 0)");
                source.AppendLine("        {");
                source.Append("            value.@").Append(step.Name).Append(" = ").Append(step.DeclaringType)
                    .Append(".@").Append(step.MethodName).Append("(in context");
                foreach (var input in step.OwnInputs)
                {
                    source.Append(", value.@").Append(input);
                }
                source.AppendLine(");");
                source.AppendLine("        }");
            }
            source.AppendLine("    }");
            source.AppendLine("}");
            if (hasNamespace)
            {
                source.AppendLine("}");
            }
            count++;
        }
        if (count != 0)
        {
            output.AddSource("ControlTokenDefaults.g.cs", GeneratedSourceText.From(source.ToString()));
        }
    }
}
