namespace AtomUI.Controls;

/// <summary>
/// Outline shape of an avatar frame.
/// </summary>
public enum AvatarShape
{
    /// <summary>
    /// Fully round frame; the default shape.
    /// </summary>
    Circle,
    /// <summary>
    /// Rectangular frame with rounded corners; the corner radius follows the size preset.
    /// </summary>
    Square
}