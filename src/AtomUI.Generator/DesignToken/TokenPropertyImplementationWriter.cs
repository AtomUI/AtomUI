using System.Text;

namespace AtomUI.Generator.DesignToken;

/// <summary>
/// Writes the implementing half of a token type's partial properties. The getter is a plain field read; the setter
/// drops the write when the property is frozen, which is a single null check while nothing is frozen.
/// </summary>
internal static class TokenPropertyImplementationWriter
{
    public static string Write(TokenTypeImplementationModel model)
    {
        var builder = new StringBuilder();
        builder.Append("// <auto-generated/>\n");
        builder.Append("#nullable enable\n\n");
        var indent = string.Empty;
        if (model.Namespace is not null)
        {
            builder.Append("namespace ").Append(model.Namespace).Append('\n');
            builder.Append("{\n");
            indent = "    ";
        }

        builder.Append(indent).Append("partial class ").Append(model.TypeName).Append('\n');
        builder.Append(indent).Append("{\n");
        var memberIndent = indent + "    ";
        var first = true;
        foreach (var property in model.Properties)
        {
            if (!first)
            {
                builder.Append('\n');
            }

            first = false;
            builder.Append(memberIndent).Append(property.Modifiers).Append(' ').Append(property.Type).Append(' ')
                   .Append(property.Name).Append('\n');
            builder.Append(memberIndent).Append("{\n");
            foreach (var accessor in property.Accessors)
            {
                builder.Append(memberIndent).Append("    ");
                if (accessor.Modifiers.Length != 0)
                {
                    builder.Append(accessor.Modifiers).Append(' ');
                }

                builder.Append(accessor.Keyword);
                if (accessor.Keyword == "get")
                {
                    builder.Append(" { OnRead(nameof(").Append(property.Name).Append(")); return field; }\n");
                }
                else
                {
                    builder.Append(" { if (IsFrozen(nameof(").Append(property.Name).Append("))) return; field = value; }\n");
                }
            }

            builder.Append(memberIndent).Append("}\n");
        }

        builder.Append(indent).Append("}\n");
        if (model.Namespace is not null)
        {
            builder.Append("}\n");
        }

        return builder.ToString();
    }
}
