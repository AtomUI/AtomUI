def findings_of(sources):
    """Return every finding of a scope built from (file name, text) pairs."""
    results = [("src/Lib/" + name, COMMENTS.analyze("src/Lib/" + name, text)) for name, text in sources]
    findings = COMMENTS.missing_comment_findings(results)
    for _, (file_findings, _) in results:
        findings.extend(file_findings)
    return findings


def messages_of(sources, rule):
    """Return the sorted messages of one rule in a scope built from (file name, text) pairs."""
    return sorted(message for found, _, _, message in findings_of(sources) if found == rule)


class ScannerTests(unittest.TestCase):
    def test_comment_markers_inside_literals_are_not_comments(self):
        code, _, comments = COMMENTS.scan_csharp(
            'var a = "http://host/x"; // real\n'
            'var b = $"{new Uri("http://host/y")}"; // tail\n'
            "var c = '\"'; // quote\n")
        self.assertEqual([comment[3] for comment in comments], ["// real", "// tail", "// quote"])
        self.assertTrue(code[1].rstrip().endswith('}\";'))

    def test_a_generated_marker_inside_a_string_does_not_hide_a_file(self):
        emitted = (
            "namespace N;\n\npublic sealed class SampleGenerator\n{\n    public void Initialize()\n    {\n"
            '        const string emitted = """\n            // <auto-generated />\n'
            "            namespace N.Generated;\n"
            '            """;\n'
            "    }\n}\n")
        self.assertFalse(COMMENTS.is_generated(emitted, "src/Lib/SampleGenerator.cs"))
        self.assertTrue(COMMENTS.is_generated("// <auto-generated />\n" + emitted, "src/Lib/Sample.cs"))
        self.assertTrue(COMMENTS.is_generated("<!-- <autogenerated /> -->\n", "src/Lib/A.axaml"))
        self.assertEqual(messages_of([("SampleGenerator.cs", emitted)], "R6"),
                         ["method SampleGenerator.Initialize has no XML comment",
                          "type SampleGenerator has no XML comment"])

    def test_literals_that_span_lines_do_not_hide_declarations(self):
        _, solid, comments = COMMENTS.scan_csharp(
            'var w = @"a""b\npublic class Fake\n{\n";\n'
            'var r = """\n// not a comment {\n""";\n')
        self.assertEqual(comments, [])
        self.assertNotIn("Fake", "\n".join(solid))
        self.assertNotIn("not a comment", "\n".join(solid))

    def test_comment_kinds(self):
        _, _, comments = COMMENTS.scan_csharp("/// doc\n//// not doc\n/** block doc */\n/* block */\n// 中文\n")
        self.assertEqual([comment[4] for comment in comments], ["doc", "line", "doc", "block", "line"])

    def test_comment_free_keeps_code_and_drops_comments(self):
        before = "/// <summary>\n/// Old.\n/// </summary>\npublic int A { get; set; } // note\n"
        after = "// 中文\npublic int A { get; set; }\n"
        self.assertEqual(COMMENTS.comment_free("A.cs", before), COMMENTS.comment_free("A.cs", after))
        self.assertNotEqual(COMMENTS.comment_free("A.cs", after), COMMENTS.comment_free("A.cs", "public int A { get; }\n"))


