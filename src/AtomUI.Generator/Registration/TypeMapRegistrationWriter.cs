using System.Text;
using AtomUI.Generator.Diagnostics;
using Microsoft.CodeAnalysis;

namespace AtomUI.Generator;

internal static class TypeMapRegistrationWriter
{
    internal static void Write(
        GenerationOutput context,
        RegistrationPackage package,
        Func<string, string>? keyHash = null,
        bool supportsTypeMap = true,
        HashSet<string>? criticalControls = null)
    {
        if (package.Controls.Count == 0 && package.Assets.Count == 0)
        {
            return;
        }

        var groupName = "ControlPackageGroup_" + RegistrationNames.Hash(package.AssemblyIdentity);
        var (mapEntries, collisions) = CreateMapEntries(package, groupName, keyHash ?? RegistrationNames.Hash);
        if (collisions.Count != 0)
        {
            foreach (var collision in collisions)
            {
                context.ReportDiagnostic(Diagnostic.Create(
                    AtomUIDiagnosticDescriptors.RegistrationIdentityConflict,
                    Location.None,
                    collision));
            }
            return;
        }
        if (!supportsTypeMap && !ConditionalRegistrationWriter.Write(context, package, groupName))
        {
            return;
        }
        if (!supportsTypeMap && criticalControls is { Count: > 0 })
        {
            // 条件（net8）后端只有单段 Collect 模板，没有分区孪生——分区发射会引用不存在的
            // CollectCritical/CollectDeferred 导致产物不可编译且错误不指向根因。显式降级为
            // 不分区并诊断告知（不静默）。
            context.ReportDiagnostic(Diagnostic.Create(
                AtomUIDiagnosticDescriptors.RegistrationStagingFallback,
                Location.None,
                "AtomUICriticalControls requires the TypeMap registration backend; the conditional (net8) " +
                "backend ignores critical controls and registers the package in one stage."));
            criticalControls = null;
        }
        context.AddSource(
            "GeneratedTypeMapRegistration.g.cs",
            GeneratedSourceText.From(Build(package, groupName, mapEntries, supportsTypeMap, criticalControls)));
    }

    private static string Build(RegistrationPackage package, string groupName, IReadOnlyList<TypeMapEntry> mapEntries,
        bool supportsTypeMap, HashSet<string>? criticalControls)
    {
        // 分区判定（分级启动）：关键集属性非空且为真子集时才分区发射。
        var partitioned = criticalControls is { Count: > 0 } &&
                          package.Controls.Any(c => !CriticalControlMatcher.IsCritical(c, criticalControls)) &&
                          package.Controls.Any(c => CriticalControlMatcher.IsCritical(c, criticalControls));

        var source = new StringBuilder("// <auto-generated />\n#nullable enable\n");
        var group = "global::" + package.Namespace + "." + groupName;
        source.Append("[assembly: global::AtomUI.Registration.ControlPackageMarker(").Append(L(package.Id)).Append(", typeof(").Append(group).AppendLine("), 1)]");
        // Conditional TypeMap annotations are interpreted by the pinned ILLink/ILC implementations.
        // Their experimental/trim diagnostics are suppressed only at these generated declarations.
        if (supportsTypeMap)
        {
            source.AppendLine("#pragma warning disable IL2026, IL3050, SYSLIB5004 // Conditional TypeMap metadata, consumed by ILLink/ILC.");
            foreach (var entry in mapEntries)
            {
                source.Append("[assembly: global::System.Runtime.InteropServices.TypeMap<").Append(group).Append(">(")
                    .Append(L(entry.Key)).Append(", typeof(global::").Append(package.Namespace).Append('.').Append(RegistrationNames.Proxy(entry.Control))
                    .Append("), typeof(").Append(entry.Trigger).AppendLine("))]");
            }
            source.AppendLine("#pragma warning restore IL2026, IL3050, SYSLIB5004");
        }
        source.Append("namespace ").Append(package.Namespace).AppendLine(";");
        source.AppendLine("[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
        source.Append("public sealed class ").Append(groupName).AppendLine("\n{");
        source.Append("    private ").Append(groupName).AppendLine("() { }");
        source.AppendLine("    // ABI v1: Browser backend resolves this helper from the marker's Group, never by a global short-name search.");
        source.AppendLine("    internal static class BrowserMap\n    {");
        source.AppendLine("        public static global::System.Collections.Generic.Dictionary<string, global::System.Type> Create() => new(global::System.StringComparer.Ordinal);");
        source.AppendLine("        public static void Add(global::System.Collections.Generic.Dictionary<string, global::System.Type> map, string key, global::System.RuntimeTypeHandle handle) => map.Add(key, global::System.Type.GetTypeFromHandle(handle)!);");
        source.AppendLine("        [global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.NoInlining)]");
        source.AppendLine("        public static global::System.Collections.Generic.IReadOnlyDictionary<string, global::System.Type> Complete(global::System.Collections.Generic.Dictionary<string, global::System.Type> map) => map;");
        source.AppendLine("    }\n}");
        source.AppendLine("internal static partial class GeneratedControlPackageRegistration\n{");
        if (supportsTypeMap)
        {
            if (partitioned)
            {
                // 分区发射（分级启动）：关键集/余量两段取代全量清单（合集与全量逐项等价），
                // 不发射全量数组——分区路径不引用它，发射即死数据（AOT 静态体积）。
                source.AppendLine("    private static readonly string[] CandidateKeysCritical = new string[]\n    {");
                foreach (var entry in mapEntries)
                {
                    if (CriticalControlMatcher.IsCritical(entry.Control, criticalControls!))
                    {
                        source.Append("        ").Append(L(entry.Key)).AppendLine(",");
                    }
                }
                source.AppendLine("    };");
                source.AppendLine("    private static readonly string[] CandidateKeysDeferred = new string[]\n    {");
                foreach (var entry in mapEntries)
                {
                    if (!CriticalControlMatcher.IsCritical(entry.Control, criticalControls!))
                    {
                        source.Append("        ").Append(L(entry.Key)).AppendLine(",");
                    }
                }
                source.AppendLine("    };");
            }
            else
            {
                source.AppendLine("    private static readonly string[] CandidateKeys = new string[]\n    {");
                foreach (var entry in mapEntries)
                {
                    source.Append("        ").Append(L(entry.Key)).AppendLine(",");
                }
                source.AppendLine("    };");
            }
        }
        if (partitioned)
        {
            // 分区发射（分级启动）：关键集先行 + 余量委托。未分区包保持既有入口原样；
            // 分区包调用独立 ABI 方法，避免新增重载破坏既有 lambda 调用的源码解析。
            source.AppendLine("    internal static global::AtomUI.IAtomUIBuilder Register(global::AtomUI.IAtomUIBuilder builder,");
            source.AppendLine("        global::System.Func<global::AtomUI.Theme.Resources.IControlThemesProvider> createProvider,");
            source.AppendLine("        global::System.Action<global::AtomUI.IAtomUIBuilder>? prepare = null, global::System.Action<global::AtomUI.IAtomUIBuilder>? complete = null)");
            source.Append("        => global::AtomUI.Registration.ControlRegistrationRuntime.RegisterPartitionedPackage(builder, ").Append(L(package.Id))
                .AppendLine(", createProvider, CollectCritical, CollectDeferred, prepare, complete);");
            source.AppendLine("    internal static global::AtomUI.IAtomUIBuilder Ensure(global::AtomUI.IAtomUIBuilder builder,");
            source.AppendLine("        global::System.Func<global::AtomUI.Theme.Resources.IControlThemesProvider> createProvider,");
            source.AppendLine("        global::System.Action<global::AtomUI.IAtomUIBuilder>? prepare = null, global::System.Action<global::AtomUI.IAtomUIBuilder>? complete = null)");
            source.Append("        => global::AtomUI.Registration.ControlRegistrationRuntime.EnsurePartitionedPackage(builder, ").Append(L(package.Id))
                .AppendLine(", createProvider, CollectCritical, CollectDeferred, prepare, complete);");
        }
        else
        {
            source.AppendLine("    internal static global::AtomUI.IAtomUIBuilder Register(global::AtomUI.IAtomUIBuilder builder,");
            source.AppendLine("        global::System.Func<global::AtomUI.Theme.Resources.IControlThemesProvider> createProvider,");
            source.AppendLine("        global::System.Action<global::AtomUI.IAtomUIBuilder>? prepare = null, global::System.Action<global::AtomUI.IAtomUIBuilder>? complete = null)");
            source.Append("        => global::AtomUI.Registration.ControlRegistrationRuntime.RegisterPackage(builder, ").Append(L(package.Id)).AppendLine(", createProvider, Collect, prepare, complete);");
            source.AppendLine("    internal static global::AtomUI.IAtomUIBuilder Ensure(global::AtomUI.IAtomUIBuilder builder,");
            source.AppendLine("        global::System.Func<global::AtomUI.Theme.Resources.IControlThemesProvider> createProvider,");
            source.AppendLine("        global::System.Action<global::AtomUI.IAtomUIBuilder>? prepare = null, global::System.Action<global::AtomUI.IAtomUIBuilder>? complete = null)");
            source.Append("        => global::AtomUI.Registration.ControlRegistrationRuntime.EnsurePackage(builder, ").Append(L(package.Id)).AppendLine(", createProvider, Collect, prepare, complete);");
        }
        if (supportsTypeMap)
        {
            var collectName = partitioned ? "CollectCritical" : "Collect";
            source.Append("    private static void ").Append(collectName).AppendLine("(global::AtomUI.Registration.ControlPackageRegistrationBuilder builder)\n    {");
            source.AppendLine("        if (global::AtomUI.Registration.ControlRegistrationRuntime.IsTrimmed)\n        {");
            source.Append("            global::AtomUI.Registration.ControlRegistrationRuntime.CollectFragments(builder, GetTypeMap(), ").Append(partitioned ? "CandidateKeysCritical" : "CandidateKeys").AppendLine(");");
            source.AppendLine("        }\n        else\n        {");
            // 完整常量只描述非裁剪包；Core 在余量消费前拒绝组合，完整收集后恢复快路径。
            // 裁剪路径按实际选中 schema 计算，不能把未保留的 fragment 纳入 Revision 证据。
            source.AppendLine("            builder.PackageSchemaFingerprint = GeneratedRegistrationFactories.PackageSchemaFingerprint;");
            foreach (var control in package.Controls)
            {
                if (partitioned && !CriticalControlMatcher.IsCritical(control, criticalControls!))
                {
                    continue;
                }
                source.Append("            new ").Append(RegistrationNames.Proxy(control)).AppendLine("().Add(builder);");
            }
            source.AppendLine("        }\n    }");
            if (partitioned)
            {
                source.AppendLine("    private static void CollectDeferred(global::AtomUI.Registration.ControlPackageRegistrationBuilder builder)\n    {");
                source.AppendLine("        if (global::AtomUI.Registration.ControlRegistrationRuntime.IsTrimmed)\n        {");
                source.AppendLine("            global::AtomUI.Registration.ControlRegistrationRuntime.CollectFragments(builder, GetTypeMap(), CandidateKeysDeferred);");
                source.AppendLine("        }\n        else\n        {");
                foreach (var control in package.Controls)
                {
                    if (CriticalControlMatcher.IsCritical(control, criticalControls!))
                    {
                        continue;
                    }
                    source.Append("            new ").Append(RegistrationNames.Proxy(control)).AppendLine("().Add(builder);");
                }
                source.AppendLine("        }\n    }");
            }
        }
        else
        {
            ConditionalRegistrationWriter.WriteCollector(source, package);
        }
        if (supportsTypeMap)
        {
            source.Append("    [global::AtomUI.Registration.GeneratedTypeMapAccessor(typeof(").Append(group).AppendLine("))]");
            source.Append("    [global::System.Diagnostics.CodeAnalysis.DynamicDependency(global::System.Diagnostics.CodeAnalysis.DynamicallyAccessedMemberTypes.PublicMethods, typeof(").Append(group).AppendLine(".BrowserMap))]");
            source.AppendLine("    internal static global::System.Collections.Generic.IReadOnlyDictionary<string, global::System.Type> GetTypeMap()");
            source.Append("        => global::System.Runtime.InteropServices.TypeMapping.GetOrCreateExternalTypeMapping<").Append(group).AppendLine(">();");
        }
        source.AppendLine("}");
        foreach (var control in package.Controls)
        {
            var proxy = RegistrationNames.Proxy(control);
            source.Append('[').Append(proxy).AppendLine("]");
            source.Append("internal sealed class ").Append(proxy).AppendLine(" : global::AtomUI.Registration.ControlRegistrationFragmentAttribute\n{");
            if (control.TokenFactory is not null || control.SemanticFactory is not null)
            {
                source.AppendLine("    // The nested holder initializes only after this fragment's platform guards pass.");
                source.AppendLine("    private static class CachedDescriptors\n    {");
                if (control.TokenFactory is not null)
                {
                    WriteCachedDescriptor(source, "Token", "global::AtomUI.Theme.Schema.ControlTokenDescriptor",
                        "GeneratedThemeSchemaDescriptorFactory." + control.TokenFactory + "()");
                }
                if (control.SemanticFactory is not null)
                {
                    WriteCachedDescriptor(source, "Semantic", "global::AtomUI.Theme.Schema.ControlSemanticDescriptor",
                        "GeneratedSemanticPartManifest." + control.SemanticFactory + "()");
                }
                source.AppendLine("    }");
            }
            source.Append("    public override string FragmentId => ").Append(L(package.Id + ":" + control.Type.AssemblyQualifiedName)).AppendLine(";");
            source.AppendLine("    public override void Add(global::AtomUI.Registration.ControlPackageRegistrationBuilder builder)\n    {");
            foreach (var guard in control.Guards)
            {
                source.Append("        if (").Append(guard).AppendLine(") return;");
            }

            if (control.TokenFactory is not null)
            {
                source.AppendLine("        builder.AddControl(CachedDescriptors.Token);");
            }

            if (control.SemanticFactory is not null)
            {
                source.AppendLine("        builder.AddSemanticControl(CachedDescriptors.Semantic);");
            }

            foreach (var asset in package.Assets.Where(a => control.Assets.Contains(a.Id)))
            {
                WriteAssetReference(source, asset, "        ");
            }

            source.AppendLine("    }\n}");
        }
        source.AppendLine("internal static class GeneratedRegistrationFactories\n{");
        // Compile-time schema identity of this package's registered controls and assets. Core combines
        // the per-package constants into the startup registry revision without re-walking the schema;
        // a hand-registered package carries no constant and falls the revision back to the full walk.
        source.Append("    internal const ulong PackageSchemaFingerprint = 0x")
              .Append(package.PackageSchemaFingerprint.ToString("X16")).AppendLine("UL;");
        if (package.Assets.Any(asset => asset.Exports.Count != 0))
        {
            // Compile-time global schema evidence: FNV-1a prefix states over the compiled global token
            // names, precomputed here so runtime asset materialization continues from the prefix instead
            // of re-hashing the names per asset. Values must match Core HashGlobalTokenNames bit-for-bit.
            source.Append("    internal const ulong CompiledContractFingerprintPrefix = 0x")
                  .Append(package.CompiledContractFingerprintPrefix.ToString("X16")).AppendLine("UL;");
            source.Append("    internal const ulong CompiledResourceKeyFingerprintPrefix = 0x")
                  .Append(package.CompiledResourceKeyFingerprintPrefix.ToString("X16")).AppendLine("UL;");
        }
        foreach (var asset in package.Assets)
        {
            source.Append("    internal static void AddAsset_").Append(RegistrationNames.Hash(asset.Id)).AppendLine("(global::AtomUI.Registration.ControlPackageRegistrationBuilder builder)\n    {");
            foreach (var guard in asset.Guards)
            {
                source.Append("        if (").Append(guard).AppendLine(") return;");
            }

            WriteAssetRegistration(source, asset, "        ");
            source.AppendLine("    }");
            source.Append("    internal static global::Avalonia.Controls.IResourceProvider ").Append(RegistrationNames.AssetFactory(asset.Id));
            if (asset.DeferredThemeTarget is { } target)
            {
                source.AppendLine("()\n    {");
                source.AppendLine("        var resources = new global::Avalonia.Controls.ResourceDictionary();");
                // Equivalent to the compiled keyed typed-theme entry: its constructor loads
                // authored AXAML with its own root services, then the wrapper sets TargetType.
                // AddDeferred retains first-lookup construction and per-dictionary caching.
                source.Append("        resources.AddDeferred(typeof(").Append(target.Name).Append("), static _ => new ")
                    .Append(asset.Wrapper).Append(" { TargetType = typeof(").Append(target.Name).AppendLine(") });");
                source.AppendLine("        return resources;\n    }");
            }
            else
            {
                source.Append("() => new ").Append(asset.Wrapper).AppendLine("();");
            }
            // The model builder emits exports/owners/bindings in the exact canonical order the runtime
        // descriptor's public constructor would establish, so the generated factory uses the presorted
        // entry: the runtime asserts the order in O(n) instead of re-sorting every asset.
        source.Append("    internal static global::AtomUI.Theme.Schema.ControlThemeAssetDescriptor ").Append(RegistrationNames.AssetDescriptor(asset.Id)).AppendLine("() => global::AtomUI.Theme.Schema.ControlThemeAssetDescriptor.CreateGeneratedPreSorted(");
            source.Append("        ").Append(L(asset.Id)).Append(", new global::System.Uri(").Append(L(asset.Uri)).AppendLine("),");
            source.AppendLine("        new global::AtomUI.Theme.Schema.ControlThemeExportDescriptor[]\n        {");
            foreach (var export in asset.Exports)
            {
                source.Append("            new(typeof(").Append(export.Target.Name).Append("), ").Append(export.KeyType is null ? L(export.Key!) : "typeof(" + export.KeyType.Name + ")").AppendLine("),");
            }

            source.AppendLine("        },\n        new global::AtomUI.Theme.Schema.ControlTokenIdentity[]\n        {");
            foreach (var owner in asset.Owners)
            {
                source.Append("            ").Append(Identity(owner)).AppendLine(",");
            }

            source.AppendLine("        },\n        new global::AtomUI.Theme.Schema.ControlThemeBindingDescriptor[]\n        {");
            foreach (var binding in asset.Bindings)
            {
                source.Append("            new(").Append(Identity(binding.Owner)).Append(", ").Append(L(binding.Property)).Append(", typeof(").Append(binding.Target.Name).AppendLine(")),");
            }

            source.Append("        }, new global::AtomUI.Theme.Schema.SchemaPrefixState(CompiledContractFingerprintPrefix), new global::AtomUI.Theme.Schema.SchemaPrefixState(CompiledResourceKeyFingerprintPrefix), 0x").Append(asset.CompiledContractFingerprint.ToString("X16")).AppendLine("UL);");
            source.Append("    private static class CachedAsset_").Append(RegistrationNames.Hash(asset.Id)).AppendLine("\n    {");
            WriteCachedDescriptor(source, "Descriptor", "global::AtomUI.Theme.Schema.ControlThemeAssetDescriptor",
                RegistrationNames.AssetDescriptor(asset.Id) + "()");
            var resourceArguments = L(asset.Id) + ", global::AtomUI.Registration.ControlResourcePhase.Control, " +
                                    asset.Order + ", " + RegistrationNames.AssetFactory(asset.Id);
            var resourceCreation = package.SupportsResourceKeys && asset.ResourceKeys is { } keys
                ? "global::AtomUI.Registration.ControlThemeResourceRegistration.CreateGenerated(" + resourceArguments +
                  ", new object[] { " + string.Join(", ", keys.Select(static key => key.Type is { } type ?
                      "typeof(" + type.Name + ")" : L(key.Key!))) + " })"
                : "new global::AtomUI.Registration.ControlThemeResourceRegistration(" + resourceArguments + ")";
            WriteCachedDescriptor(source, "Resource", "global::AtomUI.Registration.ControlThemeResourceRegistration", resourceCreation);
            source.AppendLine("    }");
        }
        source.AppendLine("}");
        return source.ToString();
    }
    private static void WriteAssetReference(StringBuilder source, RegistrationAsset asset, string indent) =>
        source.Append(indent).Append("GeneratedRegistrationFactories.AddAsset_").Append(RegistrationNames.Hash(asset.Id)).AppendLine("(builder);");

    private static void WriteAssetRegistration(StringBuilder source, RegistrationAsset asset, string indent)
    {
        source.Append(indent).Append("builder.AddThemeAsset(CachedAsset_").Append(RegistrationNames.Hash(asset.Id))
            .Append(".Descriptor, CachedAsset_").Append(RegistrationNames.Hash(asset.Id)).AppendLine(".Resource);");
    }
    private static void WriteCachedDescriptor(StringBuilder source, string name, string type, string expression)
    {
        var field = "_" + char.ToLowerInvariant(name[0]) + name.Substring(1);
        // A failed factory call must retain its original exception type. Concurrent first calls may
        // construct twice, but every builder receives the same published immutable descriptor.
        source.Append("        private static ").Append(type).Append("? ").Append(field).AppendLine(";");
        source.Append("        internal static ").Append(type).Append(' ').Append(name).AppendLine("\n        {");
        source.AppendLine("            get\n            {");
        source.Append("                var cached = global::System.Threading.Volatile.Read(ref ").Append(field).AppendLine(");");
        source.AppendLine("                if (cached is not null) return cached;");
        source.Append("                var created = ").Append(expression).AppendLine(";");
        source.Append("                return global::System.Threading.Interlocked.CompareExchange(ref ").Append(field)
            .AppendLine(", created, null) ?? created;");
        source.AppendLine("            }\n        }");
    }
    private static string Identity(RegistrationOwner owner) => "global::AtomUI.Theme.Schema.ControlTokenIdentity.ForControl(typeof(" + owner.Type.Name + "), " + L(owner.Catalog) + ", " + L(owner.Id) + ")";
    private static (IReadOnlyList<TypeMapEntry> Entries, IReadOnlyList<string> Collisions) CreateMapEntries(
        RegistrationPackage package,
        string groupName,
        Func<string, string> keyHash)
    {
        var groupIdentity = package.AssemblyIdentity + "|" + package.Namespace + "." + groupName;
        var identities = new Dictionary<string, string>(StringComparer.Ordinal);
        var entries = new List<TypeMapEntry>();
        var collisions = new List<string>();
        foreach (var control in package.Controls)
        {
            foreach (var trigger in control.Triggers)
        {
            var fullIdentity = groupIdentity + "\n" + control.Type.AssemblyQualifiedName + "\n" + trigger;
            var key = RegistrationNames.TypeMapKey(
                groupIdentity,
                control.Type.AssemblyQualifiedName,
                trigger,
                keyHash);
            if (identities.TryGetValue(key, out var existing) && existing != fullIdentity)
            {
                collisions.Add($"TypeMap key collision '{key}' between '{existing}' and '{fullIdentity}'.");
                continue;
            }

            identities[key] = fullIdentity;
            entries.Add(new(control, trigger, key));
        }
        }

        return (entries, collisions);
    }

    private sealed record TypeMapEntry(RegistrationControl Control, string Trigger, string Key);
    private static string L(string value) => RegistrationNames.Literal(value);
}

/// <summary>分区判定：按控件类型简单名匹配（AtomUICriticalControls 属性值，逗号分隔）。</summary>
internal static class CriticalControlMatcher
{
    internal static bool IsCritical(RegistrationControl? control, HashSet<string> criticalControls)
    {
        // RegistrationType.Name 是全限定显示名、MetadataName 是命名空间限定名（"Ns.Button"）；
        // 关键集属性按控件简单名匹配（截取最后 '.'/'+' 段，嵌套类型取内层名）。
        if (control?.Type?.MetadataName is not { } qualified || qualified.Length == 0)
        {
            return false;
        }
        var separator = qualified.LastIndexOfAny(['.', '+']);
        var simpleName = separator < 0 ? qualified : qualified.Substring(separator + 1);
        return criticalControls.Contains(simpleName);
    }
}
