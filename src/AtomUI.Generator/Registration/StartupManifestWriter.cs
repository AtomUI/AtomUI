using System.Text;
using AtomUI.Startup.Data;
using AtomUI.SourceGeneration;

namespace AtomUI.Generator;

internal static class StartupManifestWriter
{
    internal static void WriteEmpty(GenerationOutput output, RegistrationPackage package)
    {
        var source = new StringBuilder("// <auto-generated />\n#nullable enable\n");
        var keys = Array.Empty<TypeMapRegistrationWriter.TypeMapEntry>();
        WriteAttribute(source, package, keys);
        source.Append("namespace ").Append(package.Namespace).AppendLine(";\ninternal static class GeneratedControlPackageRegistration\n{");
        var data = StartupManifestCodec.Encode(Create(package, keys));
        source.Append("    internal static readonly global::AtomUI.Registration.ControlPackageDefinition Definition = new(")
            .Append(L(package.Id)).Append(", ").Append(L(data)).Append(", static _ => null, static _ => false");
        if (package.HasLanguageModule)
        {
            source.Append(", static builder => GeneratedLanguageModuleRegistration.Register(builder.Localization)");
        }
        source.AppendLine(");\n}");
        output.AddSource("GeneratedStartupPackageManifest.g.cs", GeneratedSourceText.From(source.ToString()));
    }

    internal static StartupPackageData Create(RegistrationPackage package,
        IReadOnlyList<TypeMapRegistrationWriter.TypeMapEntry> keys)
    {
        var assembly = SimpleAssembly(package.AssemblyIdentity);
        var controls = package.Controls.Select(control => new StartupControlData(control.Catalog, control.Id,
            control.Type.MetadataName, keys.Where(key => key.Control == control)
                .OrderBy(key => key.Trigger == control.Type.Name ? 0 : 1).ThenBy(key => key.Key, StringComparer.Ordinal)
                .Select(key => key.Key),
            control.OwnTokens.Select(token => new StartupTokenData(token.Name, token.ValueType, token.KeyType, token.KeyMember, assembly)),
            control.SemanticFactory is not null, control.TokenFactory is not null, control.Assets, SimpleAssembly(control.Type.AssemblyIdentity),
            control.SemanticThemes.Select(theme => new StartupSemanticThemeData(theme.Property,
                SimpleAssembly(theme.Target.AssemblyIdentity), theme.Target.MetadataName))));
        var assets = package.Assets.OrderBy(asset => asset.Order).ThenBy(asset => asset.Id, StringComparer.Ordinal)
            .Select(asset => new StartupAssetData(asset.Id, asset.Uri, 1, asset.Order,
            asset.ResourceKeys?.Select(key => key.Type is { } type ? TypeKey(type) : "s:" + key.Key),
            asset.Owners.Select(owner => owner.Catalog + ":" + owner.Id),
            asset.Bindings.Select(binding => binding.Owner.Catalog + ":" + binding.Owner.Id).Distinct(StringComparer.Ordinal),
            asset.Exports.Select(export => export.KeyType is { } type ? TypeKey(type) :
                export.Key is { } name ? "s:" + name : TypeKey(export.Target)),
            asset.Owners.Select(Owner), asset.Bindings.Select(binding => new StartupSemanticBindingData(Owner(binding.Owner),
                new StartupSemanticThemeData(binding.Property, SimpleAssembly(binding.Target.AssemblyIdentity), binding.Target.MetadataName)))));
        return new StartupPackageData(package.Id, assembly, controls, assets, package.PackageSchemaFingerprint, package.CompiledGlobalTokenNames);
    }

    internal static void WriteAttribute(StringBuilder source, RegistrationPackage package,
        IReadOnlyList<TypeMapRegistrationWriter.TypeMapEntry> keys)
    {
        source.Append("[assembly: global::AtomUI.Registration.ControlPackageManifest(").Append(StartupManifestCodec.Version).Append(", ")
            .Append(L(package.Id)).Append(", ").Append(L(StartupManifestCodec.Encode(Create(package, keys)))).AppendLine(")]");
    }

    internal static void WriteDefinition(StringBuilder source, RegistrationPackage package,
        IReadOnlyList<TypeMapRegistrationWriter.TypeMapEntry> keys, bool supportsTypeMap)
    {
        var data = StartupManifestCodec.Encode(Create(package, keys));
        source.Append("    private static readonly global::AtomUI.Registration.ControlPackageDefinition PackageDefinition = new(")
            .Append(L(package.Id)).Append(", ").Append(L(data)).Append(", ResolveFragment, ContainsFragment");
        if (package.HasLanguageModule)
        {
            source.Append(", static builder => GeneratedLanguageModuleRegistration.Register(builder.Localization)");
        }
        else
        {
            source.Append(", null");
        }
        source.Append(", containsAsset: ContainsAsset");
        var warmSelection = supportsTypeMap && keys.Count != 0;
        if (warmSelection)
        {
            source.Append(", warmSelection: WarmSelection");
        }
        source.AppendLine(");");
        source.AppendLine("    internal static global::AtomUI.Registration.ControlPackageDefinition Definition => PackageDefinition;");
        if (warmSelection)
        {
            source.AppendLine("    private static void WarmSelection()\n    {");
            source.AppendLine("        if (global::AtomUI.Registration.ControlRegistrationRuntime.IsTrimmed && global::System.Runtime.CompilerServices.RuntimeFeature.IsDynamicCodeCompiled)\n        {");
            // One constant-key lookup creates the external map even when this particular key
            // was trimmed. Do not resolve a proxy or enumerate the candidate-key array here.
            source.Append("            GetSelectionMap().TryGetValue(").Append(L(keys[0].Key)).AppendLine(", out _);");
            source.AppendLine("        }\n    }");
        }
        source.AppendLine("    private static bool ContainsAsset(string id)\n    {\n        switch (id)\n        {");
        foreach (var asset in package.Assets)
        {
            source.Append("            case ").Append(L(asset.Id)).AppendLine(":");
            foreach (var guard in asset.Guards)
            {
                source.Append("                if (").Append(guard).AppendLine(") { return false; }");
            }
            source.AppendLine("                return true;");
        }
        source.AppendLine("            default: return false;\n        }\n    }");
        source.AppendLine("    private static bool ContainsFragment(string key)\n    {");
        var guarded = keys.Where(key => key.Control.Guards.Count != 0).ToArray();
        if (guarded.Length != 0)
        {
            source.AppendLine("        switch (key)\n        {");
            foreach (var entry in guarded)
            {
                source.Append("            case ").Append(L(entry.Key)).AppendLine(":");
                foreach (var guard in entry.Control.Guards)
                {
                    source.Append("                if (").Append(guard).AppendLine(") { return false; }");
                }
                source.AppendLine("                break;");
            }
            source.AppendLine("        }");
        }
        source.AppendLine("        if (!global::AtomUI.Registration.ControlRegistrationRuntime.IsTrimmed) { return true; }");
        // NativeAOT TypeMapLazyDictionary only implements TryGetValue; its ContainsKey throws.
        source.AppendLine(supportsTypeMap ? "        return GetSelectionMap().TryGetValue(key, out _);" : "        return SelectedFragments.Value.Contains(key);");
        source.AppendLine("    }");
        source.AppendLine("    private static global::AtomUI.Registration.ControlRegistrationFragmentAttribute? ResolveFragment(string key)\n    {");
        source.AppendLine("        if (global::AtomUI.Registration.ControlRegistrationRuntime.IsTrimmed)\n        {");
        source.AppendLine(supportsTypeMap
            ? "            return global::AtomUI.Registration.ControlRegistrationRuntime.ResolveFragment(GetSelectionMap(), key);"
            : "            return SelectedFragments.Value.Resolve(key);");
        source.AppendLine("        }");
        source.AppendLine("        if (key.Length != 19) { return null; }");
        source.AppendLine("        return key[3] switch\n        {");
        var buckets = keys.GroupBy(key => key.Key[3]).OrderBy(group => group.Key).ToArray();
        foreach (var bucket in buckets)
        {
            source.Append("            '").Append(bucket.Key).Append("' => Resolve_").Append(bucket.Key).AppendLine("(key),");
        }
        source.AppendLine("            _ => null\n        };\n    }");
        foreach (var bucket in buckets)
        {
            source.Append("    private static global::AtomUI.Registration.ControlRegistrationFragmentAttribute? Resolve_")
                .Append(bucket.Key).AppendLine("(string key) => key switch\n    {");
            foreach (var entry in bucket)
            {
                source.Append("        ").Append(L(entry.Key)).Append(" => new ")
                    .Append(RegistrationNames.Proxy(entry.Control)).AppendLine("(),");
            }
            source.AppendLine("        _ => null\n    };");
        }
        if (!supportsTypeMap)
        {
            source.AppendLine("    private static readonly global::System.Lazy<global::AtomUI.Registration.ControlPackageFragmentSet> SelectedFragments = new(static () => new(");
            source.AppendLine("        Collect, new global::System.Collections.Generic.KeyValuePair<string, string>[]\n        {");
            foreach (var entry in keys)
            {
                source.Append("            new(").Append(L(entry.Key)).Append(", ")
                    .Append(L(package.Id + ":" + entry.Control.Type.AssemblyQualifiedName)).AppendLine("),");
            }
            source.AppendLine("        }));");
        }
    }

    private static StartupOwnerData Owner(RegistrationOwner owner) =>
        new(owner.Catalog + ":" + owner.Id, SimpleAssembly(owner.Type.AssemblyIdentity), owner.Type.MetadataName);

    private static string SimpleAssembly(string identity) => identity.Split(',')[0];
    private static string TypeKey(RegistrationType type) => "t:" + SimpleAssembly(type.AssemblyIdentity) + "|" + type.MetadataName;
    private static string L(string value) => RegistrationNames.Literal(value);
}
