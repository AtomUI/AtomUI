using System.Collections.Immutable;
using System.Text;
using AtomUI.Build.Tasks.LocalizationBuild;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace AtomUI.Generator.Localization;

internal static class LanguageTagsSourceWriter
{
    internal static void Write(
        SourceProductionContext context,
        ImmutableArray<LanguageDataEntry> entries)
    {
        context.AddSource(
            "LanguageTags.g.cs",
            GeneratedSourceText.From(BuildLanguageTagsSource(entries)));
        context.AddSource(
            "GeneratedStandardLanguageDefinitions.g.cs",
            GeneratedSourceText.From(BuildDefinitionsSource(entries)));
    }

    private static string BuildLanguageTagsSource(ImmutableArray<LanguageDataEntry> entries)
    {
        var source = new StringBuilder();
        source.AppendLine("// <auto-generated />");
        source.AppendLine("#nullable enable");
        source.AppendLine();
        source.AppendLine("namespace AtomUI.Localization");
        source.AppendLine("{");
        source.AppendLine("    public static class LanguageTags");
        source.AppendLine("    {");

        foreach (var entry in entries.OrderBy(static entry => entry.Identifier, StringComparer.Ordinal))
        {
            // Data-file casing validation leaves deprecated language aliases unchanged.
            if (!Bcp47LanguageTagParser.TryParse(entry.Tag, out var canonicalTag))
            {
                throw new InvalidOperationException(
                    $"Validated language data tag '{entry.Tag}' cannot be canonicalized.");
            }

            source.Append("        public static global::AtomUI.Localization.LanguageTag ");
            source.Append(entry.Identifier);
            source.Append(" => global::AtomUI.Localization.LanguageTag.FromCanonical(");
            source.Append(ToStringLiteral(canonicalTag));
            source.AppendLine(");");
        }

        source.AppendLine("    }");
        source.AppendLine("}");
        return source.ToString();
    }

    private static string BuildDefinitionsSource(ImmutableArray<LanguageDataEntry> entries)
    {
        var source = new StringBuilder();
        source.AppendLine("// <auto-generated />");
        source.AppendLine("#nullable enable");
        source.AppendLine();
        source.AppendLine("namespace AtomUI.Localization");
        source.AppendLine("{");
        source.AppendLine("    internal static class GeneratedStandardLanguageDefinitions");
        source.AppendLine("    {");
        source.AppendLine("        internal static bool TryCreate(");
        source.AppendLine("            global::AtomUI.Localization.LanguageTag tag,");
        source.AppendLine("            out global::AtomUI.Localization.LanguageDefinition? definition)");
        source.AppendLine("        {");
        source.AppendLine("            switch (tag.Value)");
        source.AppendLine("            {");

        foreach (var entry in entries.OrderBy(static entry => entry.Tag, StringComparer.Ordinal))
        {
            source.Append("                case ");
            source.Append(ToStringLiteral(entry.Tag));
            source.AppendLine(":");
            source.AppendLine("                    definition = new global::AtomUI.Localization.LanguageDefinition(");
            source.Append("                        global::AtomUI.Localization.LanguageTags.");
            source.Append(entry.Identifier);
            source.AppendLine(",");
            source.Append("                        global::System.Globalization.CultureInfo.GetCultureInfo(");
            source.Append(ToStringLiteral(entry.CultureName));
            source.AppendLine("),");
            source.Append("                        ");
            source.Append(ToStringLiteral(entry.NativeName));
            source.AppendLine(",");
            source.Append("                        global::AtomUI.Localization.LanguageTextDirection.");
            source.Append(entry.IsRightToLeft ? "RightToLeft" : "LeftToRight");
            source.AppendLine(");");
            source.AppendLine("                    return true;");
        }

        source.AppendLine("                default:");
        source.AppendLine("                    definition = null;");
        source.AppendLine("                    return false;");
        source.AppendLine("            }");
        source.AppendLine("        }");
        source.AppendLine("    }");
        source.AppendLine("}");
        return source.ToString();
    }

    private static string ToStringLiteral(string value)
    {
        return SyntaxFactory.LiteralExpression(
                                SyntaxKind.StringLiteralExpression,
                                SyntaxFactory.Literal(value))
                            .ToFullString();
    }
}
