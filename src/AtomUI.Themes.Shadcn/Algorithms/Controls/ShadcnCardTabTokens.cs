using AtomUI.Desktop.Controls;
using AtomUI.Theme.Algorithms;
using AtomUI.Theme.DesignTokens;
using Avalonia;

namespace AtomUI.Themes.Shadcn.Algorithms.Controls;

internal abstract class ShadcnCardTabTokens<TToken> : IControlTokenAlgorithm<TToken>
    where TToken : AbstractCardTabToken
{
    private const double MaximumCardTabRadius = 8;

    public void EvaluateGlobal(in ThemeAlgorithmContext context, DesignToken controlGlobal)
    {
        controlGlobal.BorderRadiusSM = LimitRadius(controlGlobal.BorderRadiusSM);
        controlGlobal.BorderRadius   = LimitRadius(controlGlobal.BorderRadius);
        controlGlobal.BorderRadiusLG = LimitRadius(controlGlobal.BorderRadiusLG);
    }

    public void EvaluateOwn(in ThemeAlgorithmContext context, DesignToken effectiveGlobal, TToken token)
    {
    }

    private static CornerRadius LimitRadius(CornerRadius radius) =>
        new(Math.Min(radius.TopLeft, MaximumCardTabRadius),
            Math.Min(radius.TopRight, MaximumCardTabRadius),
            Math.Min(radius.BottomRight, MaximumCardTabRadius),
            Math.Min(radius.BottomLeft, MaximumCardTabRadius));
}

