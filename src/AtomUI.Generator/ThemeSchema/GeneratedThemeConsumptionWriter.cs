using System.Text;
using AtomUI.SourceGeneration;
using Microsoft.CodeAnalysis.CSharp;

namespace AtomUI.Generator;

/// <summary>
/// Emits <c>GeneratedThemeConsumption.g.cs</c>: the promise state of every Own Token of the package and the global Tokens its
/// theme AXAML and code consume. Test code reads these arrays to drive data-driven "does this Token have a visible effect" checks.
/// The file is emitted for every package that reaches the generator, with empty arrays when there is nothing to list.
/// </summary>
internal sealed class GeneratedThemeConsumptionWriter
{
    private readonly GenerationOutput _context;
    private readonly string _generatedNamespace;
    private readonly OwnTokenReferenceAnalysisResult _analysis;

    internal GeneratedThemeConsumptionWriter(
        GenerationOutput context,
        string? assemblyName,
        OwnTokenReferenceAnalysisResult analysis)
    {
        _context = context;
        _generatedNamespace = GeneratedCodeNamespace.ForAssembly(assemblyName);
        _analysis = analysis;
    }

    internal void Write()
    {
        _context.AddSource("GeneratedThemeConsumption.g.cs", GeneratedSourceText.From(BuildSource()));
    }

    private string BuildSource()
    {
        var source = new StringBuilder();
        source.AppendLine("// <auto-generated />");
        source.AppendLine("#nullable enable");
        source.AppendLine();
        source.Append("namespace ").Append(_generatedNamespace).AppendLine(";");
        source.AppendLine();
        source.AppendLine("internal enum OwnTokenState");
        source.AppendLine("{");
        source.AppendLine("    Active,");
        source.AppendLine("    Reserved,");
        source.AppendLine("    Unreferenced");
        source.AppendLine("}");
        source.AppendLine();
        source.AppendLine("internal readonly record struct OwnTokenEntry(string Catalog, string ControlId, string Token, OwnTokenState State, string? ReservedReason);");
        source.AppendLine();
        source.AppendLine("internal readonly record struct GlobalConsumerEntry(string Catalog, string ControlId, string GlobalToken, string Source);");
        source.AppendLine();
        source.AppendLine("internal static class GeneratedThemeConsumption");
        source.AppendLine("{");
        source.AppendLine("    public static readonly OwnTokenEntry[] OwnTokens = new OwnTokenEntry[]");
        source.AppendLine("    {");
        foreach (var entry in _analysis.OwnTokens)
        {
            source.Append("        new OwnTokenEntry(")
                  .Append(Literal(entry.Catalog)).Append(", ")
                  .Append(Literal(entry.ControlId)).Append(", ")
                  .Append(Literal(entry.Token)).Append(", OwnTokenState.")
                  .Append(entry.State).Append(", ")
                  .Append(entry.ReservedReason is null ? "null" : Literal(entry.ReservedReason))
                  .AppendLine("),");
        }

        source.AppendLine("    };");
        source.AppendLine();
        source.AppendLine("    public static readonly GlobalConsumerEntry[] GlobalConsumers = new GlobalConsumerEntry[]");
        source.AppendLine("    {");
        foreach (var consumer in _analysis.GlobalConsumers)
        {
            source.Append("        new GlobalConsumerEntry(")
                  .Append(Literal(consumer.Catalog)).Append(", ")
                  .Append(Literal(consumer.ControlId)).Append(", ")
                  .Append(Literal(consumer.GlobalToken)).Append(", ")
                  .Append(Literal(consumer.Source))
                  .AppendLine("),");
        }

        source.AppendLine("    };");
        source.AppendLine("}");
        return source.ToString();
    }

    private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, quote: true);
}
