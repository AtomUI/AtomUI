using System.Text;
using AtomUI.SourceGeneration;
using Microsoft.CodeAnalysis;

namespace AtomUI.Generator;

internal static class ControlTokenGlobalValuesWriter
{
    internal static void Write(GenerationOutput output, Compilation compilation, IEnumerable<SchemaTokenInfo> tokens)
    {
        // Only the assembly that owns the source partial projection emits its members.
        if (compilation.Assembly.GetTypeByMetadataName("AtomUI.Theme.DesignTokens.ControlTokenGlobalValues") is null)
        {
            return;
        }
        var source = new StringBuilder("// <auto-generated />\nnamespace AtomUI.Theme.DesignTokens;\n");
        source.AppendLine("public readonly ref partial struct ControlTokenGlobalValues {");
        foreach (var token in tokens.OrderBy(static token => token.Name, StringComparer.Ordinal))
        {
            source.Append("    public ").Append(token.ValueType).Append(" @").Append(token.Name)
                .Append(" => global::AtomUI.Theme.Schema.TokenValueCodec<").Append(token.ValueType)
                .Append(">.Copy(((").Append(token.DeclaringType).Append(")Source).@").Append(token.Name).AppendLine(");");
        }
        source.AppendLine("}");
        output.AddSource("ControlTokenGlobalValues.g.cs", GeneratedSourceText.From(source.ToString()));
    }
}
