using System.Text;
using AtomUI.SourceGeneration;
using Microsoft.CodeAnalysis.CSharp;

namespace AtomUI.Generator;

internal static class ControlTokenAliasesWriter
{
    internal static string MetadataType(ControlTokenInfo own) => "global::" +
        (string.IsNullOrEmpty(own.TokenNamespace) ? "" : own.TokenNamespace + ".") + "__" + own.TokenName + "AliasMetadata";

    internal static void Write(GenerationOutput output, IEnumerable<ControlThemeInfo> controls)
    {
        var source = new StringBuilder("// <auto-generated />\n");
        var count = 0;
        foreach (var control in controls.Where(static control => control.OwnToken?.Aliases.Count > 0)
                     .OrderBy(static control => control.ControlTypeName, StringComparer.Ordinal))
        {
            var own = control.OwnToken!;
            var hasNamespace = !string.IsNullOrEmpty(own.TokenNamespace);
            if (hasNamespace)
            {
                source.Append("namespace ").Append(own.TokenNamespace).AppendLine(" {");
            }
            source.Append("partial class ").Append(own.TokenName).AppendLine(" {");
            source.Append("    public static global::System.Collections.Generic.IReadOnlyList<global::AtomUI.Theme.Schema.ControlTokenAlias> GetAliases() => ")
                .Append(MetadataType(own)).AppendLine(".Aliases;");
            source.AppendLine("}");
            // The descriptor reads this neutral holder, never the user's Token type.
            source.Append("internal static class __").Append(own.TokenName).AppendLine("AliasMetadata {");
            source.AppendLine("    internal static readonly global::System.Collections.Generic.IReadOnlyList<global::AtomUI.Theme.Schema.ControlTokenAlias> Aliases =");
            source.AppendLine("        global::System.Array.AsReadOnly(new global::AtomUI.Theme.Schema.ControlTokenAlias[] {");
            foreach (var alias in own.Aliases)
            {
                source.Append("            new global::AtomUI.Theme.Schema.ControlTokenAlias(")
                    .Append(SymbolDisplay.FormatLiteral(alias.Name, true)).Append(", ")
                    .Append(SymbolDisplay.FormatLiteral(alias.CanonicalName, true)).AppendLine("),");
            }
            source.AppendLine("        });");
            source.AppendLine("}");
            if (hasNamespace)
            {
                source.AppendLine("}");
            }
            count++;
        }
        if (count != 0)
        {
            output.AddSource("ControlTokenAliases.g.cs", GeneratedSourceText.From(source.ToString()));
        }
    }
}
