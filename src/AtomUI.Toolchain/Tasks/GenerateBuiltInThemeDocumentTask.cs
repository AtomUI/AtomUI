using System.Globalization;
using System.Security.Cryptography;
using System.Text;
using AtomUI.Theme.Definitions;
using Microsoft.Build.Framework;

namespace AtomUI.Build.Tasks;

public sealed class GenerateBuiltInThemeDocumentTask : ITask
{
    [Required] public string SourcePath { get; set; } = string.Empty;
    [Required] public string SourceIdentity { get; set; } = string.Empty;
    [Required] public string GeneratedCodePath { get; set; } = string.Empty;
    public IBuildEngine BuildEngine { get; set; } = null!;
    public ITaskHost HostObject { get; set; } = null!;

    public bool Execute()
    {
        try
        {
            // Parse and hash the same bounded snapshot, including its original BOM/newlines.
            using var source = File.OpenRead(SourcePath);
            using var snapshot = new MemoryStream();
            var buffer = new byte[4096];
            int read;
            while ((read = source.Read(buffer, 0, buffer.Length)) != 0)
            {
                if (snapshot.Length + read > ThemeDocumentReaderOptions.DefaultMaxDocumentBytes)
                {
                    throw new InvalidDataException("Built-in theme exceeds the document byte limit.");
                }
                snapshot.Write(buffer, 0, read);
            }
            var bytes = snapshot.ToArray();
            snapshot.Position = 0;
            var result = ThemeDocumentReader.Read(snapshot, SourceIdentity);
            foreach (var diagnostic in result.Diagnostics)
            {
                if (diagnostic.Severity == ThemeDefinitionDiagnosticSeverity.Error)
                {
                    BuildEngine.LogErrorEvent(new BuildErrorEventArgs(null, diagnostic.Code, SourcePath,
                        diagnostic.Line, diagnostic.Column, 0, 0, diagnostic.Message, null, nameof(GenerateBuiltInThemeDocumentTask)));
                }
                else
                {
                    BuildEngine.LogWarningEvent(new BuildWarningEventArgs(null, diagnostic.Code, SourcePath,
                        diagnostic.Line, diagnostic.Column, 0, 0, diagnostic.Message, null, nameof(GenerateBuiltInThemeDocumentTask)));
                }
            }
            if (!result.Success)
            {
                InvalidateOutput();
                return false;
            }

            var code = Emit(result, Convert.ToHexString(SHA256.HashData(bytes)));
            Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(GeneratedCodePath))!);
            if (!File.Exists(GeneratedCodePath) || File.ReadAllText(GeneratedCodePath) != code)
            {
                File.WriteAllText(GeneratedCodePath, code, new UTF8Encoding(false));
            }
            return true;
        }
        catch (Exception exception)
        {
            BuildEngine.LogErrorEvent(new BuildErrorEventArgs(null, null, SourcePath,
                0, 0, 0, 0, $"Could not generate the built-in theme document: {exception.GetBaseException().Message}",
                null, nameof(GenerateBuiltInThemeDocumentTask)));
            InvalidateOutput();
            return false;
        }
    }

    private void InvalidateOutput()
    {
        try
        {
            File.Delete(GeneratedCodePath);
        }
        catch (Exception exception)
        {
            // A locked/read-only stale output cannot turn validation failure into success
            // or replace the original XML diagnostic with a cleanup exception.
            BuildEngine.LogErrorEvent(new BuildErrorEventArgs(null, null, GeneratedCodePath,
                0, 0, 0, 0, $"Could not remove the invalid generated theme document: {exception.GetBaseException().Message}",
                null, nameof(GenerateBuiltInThemeDocumentTask)));
        }
    }

    private static string Emit(ThemeDocumentReadResult result, string digest)
    {
        var document = result.Document!;
        return "// <auto-generated />\n" +
               "namespace AtomUI.Theme.Definitions;\n" +
               "internal static class BuiltInThemeDocument\n{\n" +
               $"    internal const string ContentDigest = {Literal(digest)};\n" +
               "    internal static ThemeDocumentReadResult CreateReadResult(string sourceIdentity) => new(\n" +
               $"        new ThemeDocument({Literal(document.Id)}, {Literal(document.Name)}, " +
               $"(global::AtomUI.Theme.ThemeAppearance){(int)document.Appearance}, {(document.IsDefault ? "true" : "false")},\n" +
               $"            {Algorithms(document.Algorithms)},\n            {Tokens(document.Tokens)},\n" +
               $"            [{string.Join(",\n", document.Controls.Select(Control))}], {Location(document.Location)}),\n" +
               $"        [{string.Join(",\n", result.Diagnostics.Select(Diagnostic))}]);\n}}\n";
    }

    private static string Control(ControlThemeDocument control) =>
        $"new ControlThemeDocument(new ThemeControlDocumentIdentity({Literal(control.Identity.Catalog)}, {Literal(control.Identity.Id)}), " +
        $"(global::AtomUI.Theme.Configuration.ControlAlgorithmMode){(int)control.AlgorithmMode}, " +
        $"{Algorithms(control.Algorithms)}, {Tokens(control.Tokens)}, {Location(control.Location)})";

    private static string Algorithms(IReadOnlyList<ThemeAlgorithmDocument> algorithms) =>
        "[" + string.Join(", ", algorithms.Select(algorithm =>
            $"new ThemeAlgorithmDocument((global::AtomUI.Theme.Algorithms.ThemeAlgorithm){(int)algorithm.Algorithm}, {Location(algorithm.Location)})")) + "]";

    private static string Tokens(IReadOnlyList<ThemeTokenDocument> tokens) =>
        "[" + string.Join(", ", tokens.Select(token =>
            $"new ThemeTokenDocument({Literal(token.Name)}, {Literal(token.Value)}, {Location(token.Location)})")) + "]";

    private static string Location(ThemeSourceLocation location) =>
        $"new ThemeSourceLocation(sourceIdentity, {location.Line}, {location.Column}, {Literal(location.Path)})";

    private static string Diagnostic(ThemeDefinitionDiagnostic diagnostic) =>
        $"new ThemeDefinitionDiagnostic({Literal(diagnostic.Code)}, (ThemeDefinitionDiagnosticSeverity){(int)diagnostic.Severity}, " +
        $"sourceIdentity, {diagnostic.Line}, {diagnostic.Column}, {Literal(diagnostic.Path)}, {Literal(diagnostic.Message)})";

    private static string Literal(string value)
    {
        var result = new StringBuilder("\"");
        foreach (var character in value)
        {
            if (character is >= ' ' and <= '~' && character is not '\\' and not '"')
            {
                result.Append(character);
            }
            else
            {
                result.Append("\\u").Append(((int)character).ToString("X4", CultureInfo.InvariantCulture));
            }
        }
        return result.Append('"').ToString();
    }
}
