namespace AtomUI.Desktop.Controls;

/// <summary>
/// Pseudo-class names that <see cref="BaseTabControl" /> and <see cref="BaseTabStrip" /> set for the edge the tab
/// strip is placed on.
/// </summary>
public static class TabPseudoClass
{
    /// <summary>
    /// Set while the tab strip is placed at the top edge.
    /// </summary>
    public const string Top = ":top";
    /// <summary>
    /// Set while the tab strip is placed at the right edge.
    /// </summary>
    public const string Right = ":right";
    /// <summary>
    /// Set while the tab strip is placed at the bottom edge.
    /// </summary>
    public const string Bottom = ":bottom";
    /// <summary>
    /// Set while the tab strip is placed at the left edge.
    /// </summary>
    public const string Left = ":left";
}