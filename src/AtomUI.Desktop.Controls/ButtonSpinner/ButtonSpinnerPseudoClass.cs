namespace AtomUI.Desktop.Controls;

/// <summary>
/// Names of the pseudo-classes that <see cref="ButtonSpinner" /> sets for the side its spinner buttons are on.
/// </summary>
public static class ButtonSpinnerPseudoClass
{
    /// <summary>
    /// Pseudo-class of a <see cref="ButtonSpinner" /> while its <c>ButtonSpinnerLocation</c> is
    /// <see cref="ButtonSpinnerLocation.Left" />.
    /// </summary>
    public const string Left = ":left";
    /// <summary>
    /// Pseudo-class of a <see cref="ButtonSpinner" /> while its <c>ButtonSpinnerLocation</c> is
    /// <see cref="ButtonSpinnerLocation.Right" />.
    /// </summary>
    public const string Right = ":right";
}