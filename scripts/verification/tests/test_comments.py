class RepositoryTests(unittest.TestCase):
    def setUp(self):
        self._temporary = tempfile.TemporaryDirectory()
        self.root = Path(self._temporary.name)
        self.git("init", "-q")
        self.git("config", "user.name", "Tests")
        self.git("config", "user.email", "tests@example.com")
        self.write("src/Lib/Lib.csproj", "<Project />\n")
        self.write("src/Lib/A.cs", "namespace Lib;\npublic class A { }\n")
        self.commit()

    def tearDown(self):
        self._temporary.cleanup()

    def git(self, *arguments):
        return subprocess.run(["git", "-C", str(self.root)] + list(arguments), check=True,
                              capture_output=True, text=True).stdout

    def write(self, relative, text):
        path = self.root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")

    def commit(self):
        self.git("add", "-A")
        self.git("commit", "-q", "-m", "change")

    def test_staged_files_may_not_add_violations(self):
        self.write("src/Lib/A.cs", "namespace Lib;\npublic class A { public int B { get; set; } }\n")
        self.git("add", "-A")
        self.assertEqual([found[3] for found in COMMENTS.staged_errors(self.root)],
                         ["property A.B has no XML comment"])
        self.write("src/Lib/A.cs", "namespace Lib;\n// 中文\npublic class A { }\n")
        self.git("add", "-A")
        self.assertEqual([found[0] for found in COMMENTS.staged_errors(self.root)], ["R2"])

    def test_the_staged_audit_reads_each_staged_file_once(self):
        self.write("src/Lib/A.cs", "namespace Lib;\npublic class A { }\n")
        self.write("src/Other/Other.csproj", "<Project />\n")
        self.write("src/Other/C.cs", "namespace Other;\n/// <summary>\n/// A documented class.\n/// </summary>\npublic class C { }\n")
        self.git("add", "-A")
        calls = []
        real = COMMENTS.git
        COMMENTS.git = lambda root, *arguments: calls.append(arguments) or real(root, *arguments)
        try:
            self.assertEqual(COMMENTS.staged_errors(self.root), [])
        finally:
            COMMENTS.git = real
        shown = sorted(arguments for arguments in calls if arguments[0] == "show")
        self.assertEqual(shown, [("show", ":src/Other/C.cs"), ("show", ":src/Other/Other.csproj"),
                                 ("show", "HEAD:src/Other/C.cs"), ("show", "HEAD:src/Other/Other.csproj")])

    def test_the_commit_gate_reports_staged_comment_violations(self):
        def audit():
            with contextlib.redirect_stdout(io.StringIO()), contextlib.redirect_stderr(io.StringIO()):
                return CLI.main(["--root", str(self.root), "audit", "--staged"])

        self.write("src/Lib/A.cs", "namespace Lib;\npublic class A { }\n// a note\n")
        self.git("add", "-A")
        self.assertEqual(audit(), 0)
        self.write("src/Lib/A.cs", "namespace Lib;\npublic class A { public int B { get; set; } }\n")
        self.git("add", "-A")
        self.assertEqual(audit(), 2)

    def test_staged_comment_changes_and_moved_members_pass(self):
        self.write("src/Lib/A.cs", "namespace Lib;\npublic class A { public int B { get; set; } }\n")
        self.commit()
        self.write("src/Lib/A.cs", "namespace Lib;\n// B moved to its own file.\npublic class A { }\n")
        self.write("src/Lib/B.cs", "namespace Lib;\npublic partial class A { public int B { get; set; } }\n")
