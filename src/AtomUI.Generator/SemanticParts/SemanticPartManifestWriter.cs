using System.Text;
using AtomUI.SourceGeneration;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace AtomUI.Generator;

internal sealed class SemanticPartManifestWriter
{
    private readonly GenerationOutput _context;
    private readonly string _generatedNamespace;
    private readonly string _controlCatalog;
    private readonly IReadOnlyList<SemanticControlDeclaration> _controls;
    private readonly bool _emitXmlnsDefinition;

    internal SemanticPartManifestWriter(
        GenerationOutput context,
        string? assemblyName,
        string controlCatalog,
        IReadOnlyList<SemanticControlDeclaration> controls,
        bool emitXmlnsDefinition)
    {
        _context = context;
        _generatedNamespace = GeneratedCodeNamespace.ForAssembly(assemblyName);
        _controlCatalog = controlCatalog;
        _emitXmlnsDefinition = emitXmlnsDefinition;
        _controls = controls.OrderBy(
                                static control => control.ControlType.ToDisplayString(
                                    GeneratorSymbolDisplay.FullyQualifiedType),
                                StringComparer.Ordinal)
                            .ToArray();
    }

    internal void Write()
    {
        WriteManifest();
        foreach (var control in _controls)
        {
            WriteConstants(control);
        }

        if (_controls.Count > 0)
        {
            if (_emitXmlnsDefinition)
            {
                WriteXmlnsDefinition();
            }
            foreach (var control in _controls)
            {
                WriteStyles(control);
            }
        }
    }

    private void WriteManifest()
    {
        var source = new StringBuilder();
        source.AppendLine("// <auto-generated />");
        source.AppendLine("#nullable enable");
        source.Append("namespace ").Append(_generatedNamespace).AppendLine(";");
        source.AppendLine();
        source.AppendLine("internal static class GeneratedSemanticPartManifest");
        source.AppendLine("{");
        foreach (var control in _controls)
        {
            source.Append("    internal static global::AtomUI.Theme.Schema.ControlSemanticDescriptor ").Append(GetFactoryName(control)).AppendLine("()");
            source.AppendLine("    {");
            source.AppendLine("        return");
            WriteControlDescriptor(source, control);
            source.AppendLine("    }");
        }
        source.AppendLine("}");

        _context.AddSource(
            "GeneratedSemanticPartManifest.g.cs",
            GeneratedSourceText.From(source.ToString()));
    }

    internal static string GetFactoryName(SemanticControlDeclaration control) => "CreateSemanticDescriptor_" + RegistrationNames.Hash(RegistrationType.MetadataNameOf(control.ControlType));

    private void WriteControlDescriptor(StringBuilder source, SemanticControlDeclaration control)
    {
        var controlType = control.ControlType.ToDisplayString(GeneratorSymbolDisplay.FullyQualifiedType);
        source.AppendLine("            new global::AtomUI.Theme.Schema.ControlSemanticDescriptor(");
        source.Append("                typeof(").Append(controlType).AppendLine("),");
        source.Append("                global::AtomUI.Theme.Schema.ControlTokenIdentity.ForControl(typeof(").Append(controlType).Append("), ")
              .Append(FormatStringLiteral(_controlCatalog))
              .Append(", ")
              .Append(FormatStringLiteral(control.ControlType.Name))
              .AppendLine("),");
        source.AppendLine("                new global::AtomUI.Theme.Schema.SemanticPartDescriptor[]");
        source.AppendLine("                {");
        source.AppendLine("                    new global::AtomUI.Theme.Schema.SemanticPartDescriptor(");
        source.AppendLine("                        \"root\",");
        source.AppendLine("                        \"root\",");
        source.AppendLine("                        null,");
        source.Append("                        typeof(").Append(controlType).AppendLine("),");
        source.AppendLine("                        global::AtomUI.Theme.SemanticPartCardinality.Single,");
        source.AppendLine("                        global::AtomUI.Theme.SemanticPartCustomization.Root,");
        source.AppendLine("                        null,");
        source.AppendLine("                        false,");
        source.Append("                        ").Append(FormatStringLiteral(ResolveRootSince(control))).AppendLine(",");
        source.AppendLine("                        false),");
        foreach (var part in control.Parts.OrderBy(static part => part.Path, StringComparer.Ordinal))
        {
            WritePartDescriptor(source, control, part);
        }
        source.AppendLine("                });");
    }

    /// <summary>
    /// 隐式 <c>root</c> 描述块没有自己的声明可以承载版本：它由生成器加入，而 <c>Since</c> 只存在于
    /// <c>[SemanticPart]</c> 上。因此 root 的版本取该 Control 已声明 Part 中最早的发布版本——root 随这个
    /// Control 的第一个 Part 一起引入。不得硬编码版本线或具体版本，否则会与 Part 声明不一致。
    /// </summary>
    private static string ResolveRootSince(SemanticControlDeclaration control)
    {
        return control.Parts
                      .Select(static part => part.Since)
                      .Where(static since => !string.IsNullOrWhiteSpace(since))
                      .Select(static since => since!)
                      .OrderBy(ParseReleaseVersion)
                      .FirstOrDefault() ?? string.Empty;
    }

    /// <summary>
    /// 把三段式发布版本折叠成可比较的数值，避免按字符串排序把 <c>6.10.0</c> 排在 <c>6.4.0</c> 之前。
    /// 声明校验已保证格式合法；无法解析时退回该段的最大值，使其排在有效版本之后而不改变主序。
    /// </summary>
    private static long ParseReleaseVersion(string? since)
    {
        if (string.IsNullOrWhiteSpace(since))
        {
            return long.MaxValue;
        }

        long value = 0;
        var segments = 0;
        foreach (var segment in since!.Split('.'))
        {
            if (!int.TryParse(segment, out var number) || segments == 3)
            {
                return long.MaxValue;
            }

            value = (value * 100_000) + number;
            segments++;
        }

        return segments == 3 ? value : long.MaxValue;
    }

    private static void WritePartDescriptor(
        StringBuilder source,
        SemanticControlDeclaration control,
        SemanticPartDeclaration part)
    {
        var contractType = part.ContractType?.ToDisplayString(GeneratorSymbolDisplay.FullyQualifiedType) ??
                           "global::Avalonia.Controls.Control";
        source.AppendLine("                    new global::AtomUI.Theme.Schema.SemanticPartDescriptor(");
        source.Append("                        ").Append(FormatStringLiteral(part.Name)).AppendLine(",");
        source.Append("                        ").Append(FormatStringLiteral(part.Path)).AppendLine(",");
        source.Append("                        ").Append(FormatStringLiteral(part.SelectorClass ?? string.Empty)).AppendLine(",");
        source.Append("                        typeof(").Append(contractType).AppendLine("),");
        source.Append("                        global::AtomUI.Theme.SemanticPartCardinality.")
              .Append(GetCardinalityName(part.Cardinality))
              .AppendLine(",");
        source.Append("                        global::AtomUI.Theme.SemanticPartCustomization.")
              .Append(GetCustomizationName(part.Customization))
              .AppendLine(",");
        if (part.Customization == 2 && !string.IsNullOrWhiteSpace(part.ThemePropertyName))
        {
            var themeTargetType = part.ThemeTargetType?.ToDisplayString(
                                      GeneratorSymbolDisplay.FullyQualifiedType) ?? contractType;
            source.Append("                        new global::AtomUI.Theme.Schema.ControlThemeSemanticPartDescriptor(")
                  .Append(FormatStringLiteral(part.ThemePropertyName!))
                  .Append(", ")
                  .Append("typeof(").Append(themeTargetType).Append(")")
                  .AppendLine("),");
        }
        else
        {
            source.AppendLine("                        null,");
        }
        source.Append("                        ").Append(part.CrossVisualRoot ? "true" : "false").AppendLine(",");
        source.Append("                        ").Append(FormatStringLiteral(part.Since ?? string.Empty)).AppendLine(",");
        source.Append("                        ").Append(part.RuntimeCreated ? "true" : "false").AppendLine(",");
        source.Append("                        ").Append(FormatStringLiteral(part.SelectorRoute ?? string.Empty)).AppendLine(",");
        source.Append("                        typeof(global::AtomUI.Theme.Styling.")
              .Append(SemanticPartStyleContract.GetTypeName(control, part))
              .AppendLine("),");
        source.Append("                        ")
              .Append(part.CrossNestedOwners ? "true" : "false")
              .AppendLine(",");
        source.Append("                        ")
              .Append(part.RestHidden ? "true" : "false")
              .AppendLine("),");
    }

    private void WriteConstants(SemanticControlDeclaration control)
    {
        var source = new StringBuilder();
        source.AppendLine("// <auto-generated />");
        source.AppendLine("#nullable enable");
        source.Append("namespace ").Append(_generatedNamespace).AppendLine(";");
        source.AppendLine();
        source.Append("internal static class ").Append(control.ControlType.Name).AppendLine("SemanticParts");
        source.AppendLine("{");
        source.AppendLine("    internal const string Root = \"root\";");
        foreach (var part in control.Parts.OrderBy(static part => part.Path, StringComparer.Ordinal))
        {
            var memberName = ToMemberName(part.Name);
            source.Append("    internal const string ").Append(memberName).Append(" = ")
                  .Append(FormatStringLiteral(part.Name)).AppendLine(";");
            source.Append("    internal const string ").Append(memberName).Append("Class = ")
                  .Append(FormatStringLiteral(part.SelectorClass ?? string.Empty)).AppendLine(";");
            source.Append("    internal const string ").Append(memberName).Append("SelectorRoute = ")
                  .Append(FormatStringLiteral(part.SelectorRoute ?? string.Empty)).AppendLine(";");
        }
        source.AppendLine("}");

        _context.AddSource(
            $"{control.ControlType.Name}SemanticParts.g.cs",
            GeneratedSourceText.From(source.ToString()));
    }

    private void WriteStyles(SemanticControlDeclaration control)
    {
        foreach (var part in control.Parts.OrderBy(static part => part.Path, StringComparer.Ordinal))
        {
            var source = new StringBuilder();
            var styleTypeName = SemanticPartStyleContract.GetTypeName(control, part);
            source.AppendLine("// <auto-generated />");
            source.AppendLine("#nullable enable");
            source.AppendLine("using global::Avalonia.Styling;");
            source.AppendLine();
            source.AppendLine("namespace AtomUI.Theme.Styling;");
            source.AppendLine();
            source.Append("public sealed class ").Append(styleTypeName)
                  .AppendLine(" : global::Avalonia.Styling.Style");
            source.AppendLine("{");
            source.Append("    public ").Append(styleTypeName).AppendLine("()");
            source.AppendLine("        : base(static selector => selector");
            source.AppendLine("            .Nesting()");
            AppendSelectorRoute(source, part.SelectorRoute!);
            source.AppendLine("            )");
            source.AppendLine("    {");
            source.AppendLine("    }");
            source.AppendLine("}");

            _context.AddSource(
                $"{styleTypeName}.g.cs",
                GeneratedSourceText.From(source.ToString()));
        }
    }

    private void WriteXmlnsDefinition()
    {
        var source = new StringBuilder();
        source.AppendLine("// <auto-generated />");
        source.AppendLine("#nullable enable");
        source.AppendLine();
        source.AppendLine("[assembly: global::Avalonia.Metadata.XmlnsDefinition(\"https://atomui.net\", \"AtomUI.Theme.Styling\")]");

        _context.AddSource(
            "SemanticPartXmlnsDefinition.g.cs",
            GeneratedSourceText.From(source.ToString()));
    }

    private static void AppendSelectorRoute(StringBuilder source, string selectorRoute)
    {
        var tokens = selectorRoute.Split(new[] { ' ' }, StringSplitOptions.RemoveEmptyEntries);
        foreach (var token in tokens)
        {
            if (string.Equals(token, "/template/", StringComparison.Ordinal))
            {
                source.AppendLine("            .Template()");
            }
            else if (string.Equals(token, ">", StringComparison.Ordinal))
            {
                source.AppendLine("            .Child()");
            }
            else if (string.Equals(token, ">>", StringComparison.Ordinal))
            {
                source.AppendLine("            .Descendant()");
            }
            else if (token.StartsWith(".", StringComparison.Ordinal))
            {
                source.Append("            .Class(")
                      .Append(FormatStringLiteral(token.Substring(1)))
                      .AppendLine(")");
            }
            else
            {
                throw new InvalidOperationException($"Unsupported Semantic Part selector route token '{token}'.");
            }
        }
    }

    private static string ToMemberName(string value)
    {
        return string.Concat(value.Split('.').Select(static segment =>
            segment.Length == 0
                ? string.Empty
                : char.ToUpperInvariant(segment[0]) + segment.Substring(1)));
    }

    private static string GetCardinalityName(int value)
    {
        return value switch
        {
            1 => "Optional",
            2 => "Multiple",
            _ => "Single"
        };
    }

    private static string GetCustomizationName(int value)
    {
        return value switch
        {
            0 => "Root",
            2 => "SelectorAndTheme",
            _ => "Selector"
        };
    }

    private static string FormatStringLiteral(string value)
    {
        return SymbolDisplay.FormatLiteral(value, quote: true);
    }
}
