using AtomUI.Generator.Diagnostics;
using Microsoft.CodeAnalysis;

namespace AtomUI.Generator;

/// <summary>
/// A control package's token schema digest (spec 3.3): SHA-256 over every bound control token class, in ordinal order of
/// the control, with its token names and value types. Emitted as <c>[assembly: TokenSchemaDigest("…")]</c>; a value
/// package records it and the runtime compares the two at startup.
/// </summary>
internal static class TokenSchemaDigestWriter
{
    internal const string DigestAttribute = "AtomUI.Theme.Schema.TokenSchemaDigestAttribute";
    internal const string CoversAttribute = "AtomUI.Theme.Schema.CoversTokenSchemaAttribute";
    private const string LanguageContractAttribute = "AtomUI.Theme.Definitions.Compiled.ThemeBuildLanguageAttribute";

    internal static string? Compute(IEnumerable<ControlThemeInfo> controls)
    {
        var fields = new List<string> { "AtomUI.TokenSchemaDigest", "1" };
        var count = 0;
        foreach (var control in controls.Where(static control => control.HasDescriptor && control.OwnToken is { IsTerminal: true })
                                        .OrderBy(static control => control.ControlMetadataName, StringComparer.Ordinal))
        {
            count++;
            fields.Add(control.ControlMetadataName);
            fields.Add(control.OwnToken!.TokenNamespace + "." + control.OwnToken.TokenName);
            foreach (var token in control.OwnToken.SchemaTokens.OrderBy(static token => token.Name, StringComparer.Ordinal))
            {
                fields.Add(token.Name);
                fields.Add(token.ValueType);
            }
        }

        return count == 0 ? null : ThemeBuildContracts.Digest(fields).ToLowerInvariant();
    }

    internal static void Write(GenerationOutput context, Compilation compilation, IEnumerable<ControlThemeInfo> controls)
    {
        if (compilation.GetTypeByMetadataName(DigestAttribute) is null || Compute(controls) is not { } digest)
        {
            return;
        }

        // Spec 3.3: a control package does not reference the language side (language or value packages).
        foreach (var reference in compilation.SourceModule.ReferencedAssemblySymbols)
        {
            if (reference.GetAttributes().Any(static attribute =>
                    attribute.AttributeClass?.ToDisplayString() is CoversAttribute or LanguageContractAttribute))
            {
                context.ReportDiagnostic(Diagnostic.Create(AtomUIDiagnosticDescriptors.PackageDependencyDirection, Location.None,
                    $"A control package does not reference the language side; it references '{reference.Name}'."));
            }
        }

        context.AddSource("GeneratedTokenSchemaDigest.g.cs", GeneratedSourceText.From(
            "// <auto-generated />\n[assembly: global::" + DigestAttribute + "(" + ThemeBuildContracts.Literal(digest) + ")]\n"));
    }

    /// <summary>The digest a referenced control package recorded, or <see langword="null"/>.</summary>
    internal static string? Read(IAssemblySymbol assembly) =>
        assembly.GetAttributes()
                .FirstOrDefault(static attribute => attribute.AttributeClass?.ToDisplayString() == DigestAttribute)
                ?.ConstructorArguments.FirstOrDefault().Value as string;
}
